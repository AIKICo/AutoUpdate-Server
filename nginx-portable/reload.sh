#!/bin/bash
# ==============================================================================
# اسکریپت بارگذاری مجدد کانفیگ Nginx بدون قطعی
# ==============================================================================

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
cd "$DIR"

./sbin/nginx -p "$DIR" -c conf/nginx.conf -s reload
echo "کانفیگ Nginx مجدداً بارگذاری شد."
