#!/bin/bash
# ==============================================================================
# اسکریپت توقف سرور
# ==============================================================================

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
cd "$DIR"

if [ ! -f "autoupdate.pid" ]; then
    echo "سرور در حال اجرا نیست (فایل autoupdate.pid یافت نشد)."
    exit 0
fi

./bin/autoupdate-server stop
